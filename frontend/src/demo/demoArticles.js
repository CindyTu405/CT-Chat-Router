// (L1-1) 把單篇原始資料轉成前端用格式：去掉 [[ ]] 標記，並記錄每段在去標記後答案中的 [start, end) 位置
export function parseArticle(raw) {
  const opens = raw.answer.split('[[').length - 1;
  const closes = raw.answer.split(']]').length - 1;
  const spans = [];
  let answer = '';
  let last = 0;
  const re = /\[\[([\s\S]*?)\]\]/g;
  let m;
  while ((m = re.exec(raw.answer)) !== null) {
    answer += raw.answer.slice(last, m.index);
    const start = answer.length;
    answer += m[1];
    spans.push({ text: m[1], start, end: answer.length });
    last = m.index + m[0].length;
  }
  answer += raw.answer.slice(last);

  if (opens !== spans.length || closes !== spans.length || spans.length !== raw.phrases.length) {
    throw new Error(`(L1-1) 文章 ${raw.id} 的標記數量 (${spans.length}) 與 phrases 數量 (${raw.phrases.length}) 不符`);
  }

  return {
    id: raw.id,
    topic: raw.topic,
    question: raw.question,
    answer,
    phrases: spans.map((s, i) => ({
      id: `${raw.id}-p${i}`,
      text: s.text,
      start: s.start,
      end: s.end,
      question: raw.phrases[i].question,
      answer: raw.phrases[i].answer,
    })),
  };
}

